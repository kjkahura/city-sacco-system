const ABBR = { inc: 'income', rec: 'receivable', exp: 'expense', od: 'overdraft', neg: 'negative', ns: 'non-scheduled', gl: 'GL' };
const human = (s) => s.split('_').map((w) => ABBR[w] || w).join(' ');

/**
 * Column meanings that hold wherever the name appears. Returns a
 * description or null.
 */
function convention(table, column) {
  if (column === 'id') return 'Primary key.';
  if (column === 'created_at') return 'When the row was created.';
  if (column === 'updated_at') return 'When the row last changed.';
  if (column === 'created_by') return 'The user (email) or process that created it.';
  if (column === 'updated_by') return 'The user (email) or process that last changed it.';
  if (column === 'only_row') return 'Always true: the table holds one row.';
  if (column === 'custom_fields') return 'Custom field values, as {"_setId": {"fieldId": value}} (a list of those for a grouped set).';
  if (column === 'import_id') return 'The spreadsheet import that created the row (data_imports.id), if any.';
  if (column === 'member_id') return 'The member (members.id).';
  if (column === 'loan_id' || column === 'loan_account_id') return 'The loan (loan_accounts.id).';
  if (column === 'savings_account_id') return 'The deposit account (savings_accounts.id).';
  if (column === 'share_account_id') return 'The share account (share_accounts.id).';
  if (column === 'branch_id') return 'The branch (branches.id).';
  if (column === 'centre_id') return 'The centre (centres.id).';
  if (column === 'installment_id') return 'The installment (loan_installments.id).';
  if (column === 'entry_id') return 'The journal entry that posted it (journal_entries.id); NULL when nothing was booked.';
  if (column === 'transaction_id') return 'The transaction (transactions.id).';
  if (column === 'channel_id') return 'The transaction channel (transaction_channels.id).';
  if (column === 'currency_code') return 'ISO 4217 currency code.';
  if (column === 'product_id') return table.startsWith('savings') || table === 'share_accounts' ? 'The product (its product table\'s id).' : 'The product (its product table\'s id).';
  if (column === 'is_active') return 'Whether it is in use; inactive rows stay for history.';
  if (column === 'sort_order') return 'Display order.';
  if (column === 'notes' || column === 'note') return 'Free-text notes.';
  if (column === 'name') return 'Name.';
  if (column === 'description') return 'Description.';
  if (column === 'source_note') return 'Where the figure comes from (a circular, a board resolution); the platform ships none.';
  if (/^gl_/.test(column)) return `GL account code for ${human(column.slice(3))} (gl_accounts.code).`;
  if (/_roles$/.test(column)) return `Roles that may ${human(column.replace(/_roles$/, ''))}; NULL: any role the route allows.`;
  if (/^min_/.test(column) && /(principal|term|units|amount|days)/.test(column)) return `Minimum ${human(column.slice(4))}.`;
  if (/^max_/.test(column) && /(principal|term|amount|days|tranches|overdraft_limit|credit_balance|multiplier)/.test(column)) return `Maximum ${human(column.slice(4))}.`;
  if (/_min$/.test(column)) return `Lowest ${human(column.replace(/_min$/, ''))} an account may be given.`;
  if (/_max$/.test(column)) return `Highest ${human(column.replace(/_max$/, ''))} an account may be given.`;
  return null;
}

