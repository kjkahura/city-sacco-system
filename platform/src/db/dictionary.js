function describe(table, column) {
  const key = `${table}.${column}`;
  if (COLUMNS[key]) return { text: COLUMNS[key], source: 'column' };
  if (table === 'loan_products' && PRODUCT_COLUMNS[column]) return { text: PRODUCT_COLUMNS[column], source: 'column' };
  const c = convention(table, column);
  if (c) return { text: c, source: 'convention' };
  return null;
}

